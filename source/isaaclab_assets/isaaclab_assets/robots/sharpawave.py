def _public_asset_path(path: Path) -> str:
    """Serialize an asset path without leaking the checkout's absolute root."""

    return path.relative_to(_MODULE_DIR).as_posix()


@dataclass(frozen=True)
class JointSpec:
    """A canonical actuated-joint description.

    ``lower`` and ``upper`` are copied from the URDF in radians for revolute
    joints and metres for prismatic joints.  For continuous joints the bounds
    describe the source representation; consumers must still handle wrapping
    explicitly.
    """

    name: str
    kind: str
    unit: str
    lower: float | None
    upper: float | None
    effort_limit: float | None
    velocity_limit: float | None
    source: str = "urdf"
    continuous: bool = False

    def validate_value(self, value: float) -> None:
        """Raise ``ValueError`` when a scalar is not finite or out of bounds."""

        if not math.isfinite(float(value)):
            raise ValueError(f"{self.name}: action value must be finite")
        if self.lower is not None and float(value) < self.lower:
            raise ValueError(f"{self.name}: value {value} is below {self.lower}")
        if self.upper is not None and float(value) > self.upper:
            raise ValueError(f"{self.name}: value {value} is above {self.upper}")

    def wrap_value(self, value: float) -> float:
        """Return a finite value, wrapping continuous rotations into one turn."""

        numeric = float(value)
        if not math.isfinite(numeric):
            raise ValueError(f"{self.name}: action value must be finite")
        if not self.continuous:
            self.validate_value(numeric)
            return numeric
        return (numeric + math.pi) % (2.0 * math.pi) - math.pi


@dataclass(frozen=True)
class FingertipSpec:
    """Semantic mapping for a finger pose frame and its contact body."""

    role: str
    pose_frame: str
    contact_body: str
    contact_sensor_required: bool = True
    contact_status: str = "asset_declared_runtime_unverified"


@dataclass(frozen=True)
class ActionSchema:
    """Versioned canonical action contract.

    Numeric scaling is intentionally absent until actuator calibration is
    supplied.  The profile names are still explicit so an adapter can reject
    an unsupported policy rather than silently applying another robot's scale.
    """

    schema_id: str
    joint_names: tuple[str, ...]
    units: tuple[str, ...]
    supported_profiles: tuple[str, ...] = ("joint_delta", "joint_target")
    default_profile: str = "joint_delta"
    action_scale: tuple[float, ...] | None = None
    action_offset: tuple[float, ...] | None = None
    scale_status: str = "missing_calibration"
    wrist_joint_names: tuple[str, ...] = ()
    finger_joint_names: tuple[str, ...] = ()

    @property
    def dimension(self) -> int:
        return len(self.joint_names)

    @property
    def action_dim(self) -> int:
        return self.dimension

    @property
    def wrist_action_dim(self) -> int:
        return len(self.wrist_joint_names)

    @property
    def finger_action_dim(self) -> int:
        return len(self.finger_joint_names)

    @property
    def canonical_joint_names(self) -> tuple[str, ...]:
        return self.joint_names

    def validate_profile(self, profile: str) -> None:
        if profile not in self.supported_profiles:
            raise ValueError(
                f"unsupported action profile {profile!r}; "
                f"supported={self.supported_profiles}"
            )
        if self.default_profile not in self.supported_profiles:
            raise ValueError("default action profile is not supported")


@dataclass(frozen=True)
class RuntimeSchemaReport:
    """Name-resolution result returned before an articulation is controlled."""

    valid: bool
    missing: tuple[str, ...] = ()
    duplicate_runtime_names: tuple[str, ...] = ()
    extra_runtime_names: tuple[str, ...] = ()


@dataclass(frozen=True)
class AssetValidationReport:
    """Filesystem-only validation result; no simulator is required."""

    valid: bool
    missing_paths: tuple[str, ...] = ()
    present_paths: tuple[str, ...] = ()
    warnings: tuple[str, ...] = ()


@dataclass(frozen=True)
class SharpaWaveVariantConfig:
    """Complete declarative configuration for one SharpaWave variant."""

    name: str
    schema_id: str
    urdf_path: Path
    usd_path: Path
    contact_layer_paths: tuple[Path, ...]
    base_joint_names: tuple[str, ...]
    finger_joint_names: tuple[str, ...]
    fixed_joint_names: tuple[str, ...]
    joint_specs: tuple[JointSpec, ...]
    fingertip_specs: tuple[FingertipSpec, ...]
    root_link_name: str = "base_root"
    vendor_fix_base: bool = True
    root_semantics_status: str = "runtime_unverified"
    contact_status: str = "asset_layers_present_runtime_unverified"
    actuator_control_mode: str = "position_target"
    actuator_limits_source: str = "urdf"
    actuator_gains_status: str = "missing_calibration"

    def __post_init__(self) -> None:
        expected = self.base_joint_names + self.finger_joint_names
        actual = tuple(spec.name for spec in self.joint_specs)
        if actual != expected:
            raise ValueError(
                f"{self.name}: joint_specs must match canonical action order; "
                f"expected={expected!r}, actual={actual!r}"
            )
        if len(set(actual)) != len(actual):
            raise ValueError(f"{self.name}: duplicate canonical joint name")
        if len(self.fingertip_specs) != 5:
            raise ValueError(f"{self.name}: expected five fingertip mappings")

    @property
    def action_dim(self) -> int:
        return len(self.joint_specs)

    @property
    def wrist_action_dim(self) -> int:
        """Number of variant-specific root/wrist controls."""

        return len(self.base_joint_names)

    @property
    def finger_action_dim(self) -> int:
        return len(self.finger_joint_names)

    @property
    def continuous_joint_names(self) -> tuple[str, ...]:
        return tuple(spec.name for spec in self.joint_specs if spec.continuous)

    @property
    def canonical_joint_names(self) -> tuple[str, ...]:
        return self.base_joint_names + self.finger_joint_names

    # Friendly aliases used by adapters without exposing mutable collections.
    @property
    def joint_names(self) -> tuple[str, ...]:
        return self.canonical_joint_names

    @property
    def hand_joint_names(self) -> tuple[str, ...]:
        return self.finger_joint_names

    @property
    def wrist_joint_names(self) -> tuple[str, ...]:
        return self.base_joint_names

    @property
    def variant(self) -> str:
        return self.name

    @property
    def schema_version(self) -> str:
        return self.schema_id

    @property
    def asset_path(self) -> Path:
        return self.urdf_path

    @property
    def usd_asset_path(self) -> Path:
        return self.usd_path

    @property
    def fingertip_frames(self) -> tuple[str, ...]:
        return tuple(item.pose_frame for item in self.fingertip_specs)

    @property
    def fingertip_links(self) -> tuple[str, ...]:
        return self.fingertip_frames

    @property
    def contact_body_names(self) -> tuple[str, ...]:
        return tuple(item.contact_body for item in self.fingertip_specs)

    @property
    def contact_links(self) -> tuple[str, ...]:
        return self.contact_body_names

    @property
    def action_schema(self) -> ActionSchema:
        return ActionSchema(
            schema_id=self.schema_id,
            joint_names=self.canonical_joint_names,
            units=tuple(spec.unit for spec in self.joint_specs),
            wrist_joint_names=self.base_joint_names,
            finger_joint_names=self.finger_joint_names,
        )

    def resolve_joint_indices(self, runtime_joint_names: Sequence[str]) -> tuple[int, ...]:
        """Map canonical names to runtime indices, rejecting ambiguous schemas."""

        names = tuple(str(name) for name in runtime_joint_names)
        duplicates = tuple(sorted({name for name in names if names.count(name) > 1}))
        if duplicates:
            raise ValueError(f"{self.name}: duplicate runtime joint names: {duplicates}")
        positions = {name: index for index, name in enumerate(names)}
        missing = tuple(name for name in self.canonical_joint_names if name not in positions)
        if missing:
            raise ValueError(f"{self.name}: runtime schema is missing joints: {missing}")
        return tuple(positions[name] for name in self.canonical_joint_names)

    def validate_runtime_joint_names(
        self, runtime_joint_names: Sequence[str]
    ) -> RuntimeSchemaReport:
        names = tuple(str(name) for name in runtime_joint_names)
        duplicates = tuple(sorted({name for name in names if names.count(name) > 1}))
        expected = set(self.canonical_joint_names)
        present = set(names)
        missing = tuple(name for name in self.canonical_joint_names if name not in present)
        extras = tuple(name for name in names if name not in expected)
        return RuntimeSchemaReport(
            valid=not duplicates and not missing,
            missing=missing,
            duplicate_runtime_names=duplicates,
            extra_runtime_names=extras,
        )

    def validate_files(self) -> AssetValidationReport:
        """Check declared files and mesh references without loading USD."""

        required = [self.urdf_path, self.usd_path, SHARPAWAVE_VENDOR_CONFIG_PATH]
        required.extend(self.contact_layer_paths)
        missing = tuple(_public_asset_path(path) for path in required if not path.is_file())
        present = tuple(_public_asset_path(path) for path in required if path.is_file())
        warnings: list[str] = []
        if not SHARPAWAVE_MESH_ROOT.is_dir():
            warnings.append(f"mesh root is absent: {_public_asset_path(SHARPAWAVE_MESH_ROOT)}")
        if self.vendor_fix_base:
            warnings.append("vendor config requests fix_base=true; runtime root semantics require Kit validation")
        warnings.append("contact sensor API and thresholds require runtime validation")
        return AssetValidationReport(
            valid=not missing,
            missing_paths=missing,
            present_paths=present,
            warnings=tuple(warnings),
        )

    def validate_action_shape(self, action: Any) -> tuple[int, ...]:
        """Validate a batch-first action object and return its shape.

        The method intentionally relies only on a ``shape`` attribute, so it
        accepts NumPy, Torch, and Isaac tensors without importing any of them.
        """

        shape = getattr(action, "shape", None)
        if shape is None:
            raise TypeError("action must expose a batch-first shape")
        normalized = tuple(int(value) for value in shape)
        if len(normalized) != 2 or normalized[-1] != self.action_dim:
            raise ValueError(
                f"{self.name}: expected batch-first shape (N, {self.action_dim}), got {normalized}"
            )
        return normalized

    def default_configuration(self) -> Mapping[str, Any]:
        """Return a serializable configuration snapshot for adapters/tools."""

        return {
            "robot": SHARPAWAVE_ROBOT_NAME,
            "variant": self.name,
            "schema_id": self.schema_id,
            "asset_root": "source/isaaclab_assets/isaaclab_assets/robots/sharpa-wave-description",
            "urdf_path": _public_asset_path(self.urdf_path),
            "usd_path": _public_asset_path(self.usd_path),
            "contact_layer_paths": tuple(_public_asset_path(path) for path in self.contact_layer_paths),
            "root_link_name": self.root_link_name,
            "base_joint_names": self.base_joint_names,
            "finger_joint_names": self.finger_joint_names,
            "fixed_joint_names": self.fixed_joint_names,
            "action_dim": self.action_dim,
            "action_profile": self.action_schema.default_profile,
            "action_profiles": self.action_schema.supported_profiles,
            "action_scale_status": self.action_schema.scale_status,
            "action_units": tuple(spec.unit for spec in self.joint_specs),
            "continuous_joint_names": self.continuous_joint_names,
            "joint_limits": tuple(
                {
                    "name": spec.name,
                    "kind": spec.kind,
                    "lower": spec.lower,
                    "upper": spec.upper,
                    "effort_limit": spec.effort_limit,
                    "velocity_limit": spec.velocity_limit,
                    "continuous": spec.continuous,
                }
                for spec in self.joint_specs
            ),
            "vendor_fix_base": self.vendor_fix_base,
            "root_semantics_status": self.root_semantics_status,
            "contact_status": self.contact_status,
            "actuator_control_mode": self.actuator_control_mode,
            "actuator_limits_source": self.actuator_limits_source,
            "actuator_gains_status": self.actuator_gains_status,
            "calibration_status": "missing_calibration",
            "base_pose_mapper_status": "missing_dependency",
            "policy_status": "missing_dependency",
            "contact_sensor_status": self.contact_status,
            "fingertips": tuple(
                {
                    "role": item.role,
                    "pose_frame": item.pose_frame,
                    "contact_body": item.contact_body,
                    "contact_sensor_required": item.contact_sensor_required,
                    "contact_status": item.contact_status,
                }
                for item in self.fingertip_specs
            ),
        }


