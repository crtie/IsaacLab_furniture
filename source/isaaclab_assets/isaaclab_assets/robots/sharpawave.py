def get_sharpawave_variant(name: str = SHARPAWAVE_VARIANT_FLOATING) -> SharpaWaveVariantConfig:
    """Return a configured variant or raise a useful error for typos."""

    key = str(name).strip().lower()
    try:
        return SHARPAWAVE_VARIANTS[key]
    except KeyError as exc:
        choices = ", ".join(sorted(SHARPAWAVE_VARIANTS))
        raise ValueError(f"unknown SharpaWave variant {name!r}; choose one of: {choices}") from exc


def validate_sharpawave_assets() -> Mapping[str, AssetValidationReport]:
    """Validate both declared variants using only repository filesystem state."""

    return {name: config.validate_files() for name, config in SHARPAWAVE_VARIANTS.items()}


