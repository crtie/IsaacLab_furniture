"""Declarative asset contract for the right SharpaWave hand.

This module deliberately does not import Isaac Sim/IsaacLab.  It is the
single, dependency-light source of truth for the SharpaWave asset paths,
canonical joint order, limits, fingertip frames, and the two supplied URDF
variants.  IsaacLab-specific articulation objects can be built by an adapter
without making this module import-time dependent on a simulator installation.

The canonical order in this file is intentional.  USD layers generated by
different conversion passes enumerate joints in different orders (and include
fixed helper joints), so runtime code must resolve indices by name through
``resolve_joint_indices`` instead of relying on traversal order.
"""

from __future__ import annotations

